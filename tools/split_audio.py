def clean_filename(text):
    """清理文件名中的非法字符"""
    # 只保留中文、英文、数字、下划线
    text = re.sub(r'[^\w\u4e00-\u9fff]', '_', text)
    # 长度限制
    text = text[:30]
    return text


def split_audio():
    """按等分方式分割音频"""
    
    # 加载音频
    print(f'📂 加载音频: {INPUT_WAV}')
    y, sr = librosa.load(INPUT_WAV, sr=16000)
    total_duration = len(y) / sr
    print(f'⏱️  总时长: {total_duration:.1f}秒')
    
    # 创建输出目录
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    # 计算每个片段的平均长度
    num_segments = len(TEXTS)
    samples_per_segment = len(y) // num_segments
    
    print(f'✂️  准备分割为 {num_segments} 个文件...')
    print('=' * 60)
    
    created_files = []
    
    for i, text in enumerate(TEXTS):
        start_sample = i * samples_per_segment
        end_sample = (i + 1) * samples_per_segment if i < num_segments - 1 else len(y)
        
        # 提取片段
        segment = y[start_sample:end_sample]
        
        # 生成文件名
        clean_text = clean_filename(text)
        filename = f'{i+1:03d}_{clean_text}.wav'
        filepath = os.path.join(OUTPUT_DIR, filename)
        
        # 保存为WAV (16bit, 16000Hz, mono)
        segment_int16 = (segment * 32767).astype('int16')
        with wave.open(filepath, 'wb') as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(16000)
            w.writeframes(segment_int16.tobytes())
        
        duration = len(segment) / 16000
        created_files.append((filename, duration))
        
        if (i + 1) % 50 == 0 or i == 0:
            print(f'  [{i+1:03d}/{num_segments}] {filename} ({duration:.1f}秒)')
    
    # 统计
    print('=' * 60)
    print(f'✅ 成功创建 {len(created_files)} 个文件')
    
    total_duration_created = sum(d for _, d in created_files)
    print(f'⏱️  总时长: {total_duration_created:.1f}秒 ({total_duration_created/60:.1f}分钟)')
    
    # 文件大小统计
    total_size = sum(os.path.getsize(os.path.join(OUTPUT_DIR, f)) for f in os.listdir(OUTPUT_DIR) if f.endswith('.wav'))
    print(f'💾 总大小: {total_size/1024/1024:.2f} MB')
    
    # 显示前5个和后5个文件
    print()
    print('📋 文件列表 (前5个):')
    for f, d in created_files[:5]:
        print(f'   {f} ({d:.1f}秒)')
    print('   ...')
    print('📋 文件列表 (后5个):')
    for f, d in created_files[-5:]:
        print(f'   {f} ({d:.1f}秒)')


if __name__ == '__main__':
    split_audio()
